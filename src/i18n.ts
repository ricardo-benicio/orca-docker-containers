export function translate(locale: string | undefined, key: Key, vars: Record<string, string | number> = {}): string {
  const table = locale?.toLowerCase().startsWith('pt') ? pt : en
  return table[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))
}
